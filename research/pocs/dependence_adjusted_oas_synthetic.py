"""Controlled synthetic challenge for peer predictive-target HAC-OAS.

Vary support size, row dependence, and target/peer scale compatibility. Attack
samples are held out from fitting and are generated by sparse mean shifts in
peer-scale units. This tests the score geometry under known data-generating
conditions, not a universal IoT threat model.
"""
from __future__ import annotations

import os
import sys
from pathlib import Path

os.environ.setdefault("OMP_NUM_THREADS", "1")
os.environ.setdefault("OPENBLAS_NUM_THREADS", "1")
os.environ.setdefault("MKL_NUM_THREADS", "1")

import numpy as np
import pandas as pd
from sklearn.metrics import roc_auc_score

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "research" / "pocs"))
from dependence_adjusted_oas import fit, covariance_ess
from fedorbit.detection.moments import aggregate_equal_weight, summarise

OUT = ROOT / "research" / "pocs" / "results" / "dependence_adjusted_oas_synthetic.csv"
SUPPORTS = (30, 100, 300, 1000)
REGIMES = (("iid_match", 0.0, 1.0), ("ar05_match", 0.5, 1.0),
           ("ar08_match", 0.8, 1.0), ("ar08_shifted_scale", 0.8, 1.0),
           ("ar08_target_scale_narrow", 0.8, 1.0))
REPLICATES = 40
FEATURES = 20
PEERS = 8
SEED = 202609314


def covariance(scale):
    corr = 0.45 ** np.abs(np.subtract.outer(np.arange(FEATURES), np.arange(FEATURES)))
    return corr * np.outer(scale, scale)


def ar_rows(rng, count, mean, cov, rho):
    chol = np.linalg.cholesky(cov + np.eye(len(mean)) * 1e-7)
    eps = rng.normal(size=(count, len(mean))) @ chol.T
    if rho == 0:
        return mean + eps
    out = np.empty_like(eps)
    out[0] = mean + eps[0]
    innovation_scale = np.sqrt(1.0 - rho**2)
    for t in range(1, count):
        out[t] = mean + rho * (out[t-1] - mean) + innovation_scale * eps[t]
    return out


def mean_ess(rows):
    centered = rows - rows.mean(axis=0, keepdims=True)
    n = len(rows)
    denom = np.maximum(np.sum(centered**2, axis=0), 1e-9)
    lagmax = min(n // 4, max(1, int(np.floor(4 * (n / 100.0) ** (2/9)))))
    lrv = np.ones(rows.shape[1])
    for lag in range(1, lagmax + 1):
        rho = np.sum(centered[:-lag] * centered[lag:], axis=0) / denom
        lrv += 2 * (1 - lag/(lagmax+1)) * rho
    return np.clip(n / np.maximum(lrv, 1), 2, max(n-1, 2))


def target_scale(rng, peer_predictive, regime):
    if regime == "ar08_shifted_scale":
        multiplier = np.tile(np.array([0.5, 2.0]), FEATURES // 2)
        return peer_predictive * multiplier
    if regime == "ar08_target_scale_narrow":
        multiplier = np.tile(np.array([0.5, 1.5]), FEATURES // 2)
        return peer_predictive * multiplier
    return peer_predictive.copy()


def evaluate_score(model, benign, attack):
    benign_score, attack_score = model.score(benign), model.score(attack)
    y = np.r_[np.zeros(len(benign_score)), np.ones(len(attack_score))]
    s = np.r_[benign_score, attack_score]
    return (roc_auc_score(y, s), roc_auc_score(y, s, max_fpr=0.01))


def main():
    rng = np.random.default_rng(SEED)
    records = []
    for regime, rho, _ in REGIMES:
        for n in SUPPORTS:
            for rep in range(REPLICATES):
                peer_means = rng.normal(0, 0.3, size=(PEERS, FEATURES))
                peer_within = np.exp(rng.normal(0, 0.18, size=(PEERS, FEATURES)))
                grand_mean = peer_means.mean(axis=0)
                peer_total = peer_within + (peer_means - grand_mean)**2
                peer_rows = [ar_rows(rng, 1200, peer_means[k], covariance(np.sqrt(peer_within[k])), 0.0)
                             for k in range(PEERS)]
                peer = aggregate_equal_weight([summarise(x) for x in peer_rows])
                peer_center_var = np.maximum(np.var(peer_means, axis=0, ddof=1), 1e-6)
                peer_predictive = peer.covariance.diagonal()
                scale_var = target_scale(rng, peer_predictive, regime)
                target_mean = rng.normal(0, 0.3, FEATURES)
                support = ar_rows(rng, n, target_mean, covariance(np.sqrt(scale_var)), rho)
                benign = ar_rows(rng, 500, target_mean, covariance(np.sqrt(scale_var)), rho)
                shift = np.zeros(FEATURES)
                active = rng.choice(FEATURES, size=4, replace=False)
                shift[active] = rng.choice((-1.0, 1.0), size=len(active)) * 1.5 * np.sqrt(peer_predictive[active])
                attack = ar_rows(rng, 500, target_mean + shift,
                                 covariance(np.sqrt(scale_var)), rho)
                for method in ("oas_nominal", "oas_covariance_ess", "bartz_hac",
                               "shared_marginals", "collaborative_ess_mean_oas",
                               "collaborative_bartz_mean_oas"):
                    model = fit(support, peer, method, peer_center_var)
                    auc, pauc = evaluate_score(model, benign, attack)
                    records.append({"regime": regime, "rho": rho, "support_n": n,
                                    "replicate": rep, "method": method,
                                    "auroc": auc, "spauc01": pauc,
                                    "covariance_ess": covariance_ess(
                                        (support-support.mean(axis=0))/peer.standard_deviation
                                    ),
                                    "median_mean_ess": float(np.median(mean_ess(support)))})
            print(regime, n, "done", flush=True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    frame = pd.DataFrame(records)
    frame.to_csv(OUT, index=False)
    print(frame.groupby(["regime", "support_n", "method"])[["auroc", "spauc01",
          "covariance_ess", "median_mean_ess"]].mean().round(4).to_string())
    print("wrote", len(frame), OUT)


if __name__ == "__main__":
    main()
